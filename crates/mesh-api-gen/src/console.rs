//! The method and field catalog compiled into a constrained device's console: integers and one string pool, no
//! pointers (a flash-resident module has no relocations). It names the components, methods and fields of several
//! `API.md` files so a typed line becomes tagged CBOR and an answer becomes text.
//!
//! The device-side tables are the same information as [`crate::manifest_cbor`], flattened for lookup by index.

use std::collections::BTreeMap;

use crate::{ApiField, ApiMethod};

const K_ANY: u8 = 0;
const K_TEXT: u8 = 1;
const K_BOOL: u8 = 2;
const K_UINT: u8 = 3;
const K_INT: u8 = 4;
const K_BYTES: u8 = 5;
const K_MAP: u8 = 6;
const K_ARRAY: u8 = 7;

/// `(kind, record index + 1 or 0)` of a type cell.
fn kind_of(value_type: &str, records: &BTreeMap<&str, usize>) -> (u8, usize) {
    let (array, name) = match value_type.strip_suffix("[]") {
        Some(name) => (true, name),
        None => (false, value_type),
    };
    if let Some(index) = records.get(name) {
        return (if array { K_ARRAY } else { K_MAP }, index + 1);
    }
    if array || name == "array" {
        return (K_ARRAY, 0);
    }
    let kind = match name {
        "string" | "text" => K_TEXT,
        "bool" => K_BOOL,
        "bytes" | "hex" => K_BYTES,
        "map" => K_MAP,
        "int" | "i8" | "i16" | "i32" | "i64" => K_INT,
        _ if name.starts_with('u') || name == "enum" => K_UINT,
        _ => K_ANY,
    };
    (kind, 0)
}

struct Pool {
    bytes: Vec<u8>,
    offsets: BTreeMap<String, usize>,
}

impl Pool {
    fn name(&mut self, text: &str) -> usize {
        if let Some(offset) = self.offsets.get(text) {
            return *offset;
        }
        let offset = self.bytes.len();
        self.bytes.extend_from_slice(text.as_bytes());
        self.bytes.push(0);
        self.offsets.insert(text.to_owned(), offset);
        offset
    }
}

/// The C header of the catalog of every component of `apis` that has numeric indices. `sources` names the files for the
/// header comment.
pub fn console_catalog(sources: &[String], apis: &[Vec<ApiMethod>]) -> String {
    // components in document order, record types by name
    let mut components: Vec<(&str, u32, Vec<&ApiMethod>)> = Vec::new();
    let mut types: BTreeMap<&str, &[ApiField]> = BTreeMap::new();
    for methods in apis {
        for method in methods {
            for row in &method.row_types {
                types.entry(row.name.as_str()).or_insert(row.fields.as_slice());
            }
            let (Some(component_index), Some(_)) = (method.component_index, method.method_index) else {
                continue;
            };
            match components.iter_mut().find(|(name, _, _)| *name == method.component) {
                Some((_, _, list)) => list.push(method),
                None => components.push((method.component.as_str(), component_index, vec![method])),
            }
        }
    }
    let records: BTreeMap<&str, usize> = types.keys().enumerate().map(|(i, name)| (*name, i)).collect();
    let mut pool = Pool { bytes: vec![0], offsets: BTreeMap::new() };
    let mut fields: Vec<(usize, u32, u8, usize)> = Vec::new();
    let add_fields = |pool: &mut Pool, list: &[ApiField], fields: &mut Vec<(usize, u32, u8, usize)>| {
        for f in list {
            let (kind, record) = kind_of(&f.value_type, &records);
            let name = pool.name(&f.name);
            fields.push((name, f.index, kind, record));
        }
    };
    let mut record_rows = Vec::new();
    for (name, list) in &types {
        let first = fields.len();
        add_fields(&mut pool, list, &mut fields);
        let count = fields.len() - first;
        record_rows.push((pool.name(name), first, count));
    }
    let mut method_rows = Vec::new();
    let mut component_rows = Vec::new();
    for (name, id, methods) in &components {
        let first = method_rows.len();
        for method in methods {
            let request = fields.len();
            add_fields(&mut pool, &method.request.fields, &mut fields);
            let response = fields.len();
            add_fields(&mut pool, &method.response.fields, &mut fields);
            let method_name = pool.name(&method.method);
            method_rows.push((method_name, method.method_index.unwrap_or(0), request, response - request, response, fields.len() - response));
        }
        component_rows.push((pool.name(name), *id, first, method_rows.len() - first));
    }

    let join = |rows: Vec<String>| rows.join(", ");
    let mut out = String::new();
    out.push_str(&format!("/* GENERATED by mesh-api-gen (--out-console-catalog) from {}. Do not edit. */\n#pragma once\n\n#include <stdint.h>\n\n", sources.join(", ")));
    out.push_str(&format!(
        "#define CAT_K_ANY {K_ANY}\n#define CAT_K_TEXT {K_TEXT}\n#define CAT_K_BOOL {K_BOOL}\n#define CAT_K_UINT {K_UINT}\n#define CAT_K_INT {K_INT}\n#define CAT_K_BYTES {K_BYTES}\n#define CAT_K_MAP {K_MAP}\n#define CAT_K_ARRAY {K_ARRAY}\n\n"
    ));
    out.push_str("/* names: NUL-terminated strings, 16-bit offsets into this pool */\n");
    out.push_str(&format!(
        "static const uint8_t cat_pool[{}] = {{{}}};\n",
        pool.bytes.len(),
        join(pool.bytes.iter().map(|b| format!("0x{b:02x}")).collect())
    ));
    out.push_str("typedef struct { uint16_t name, id, first, count; } cat_comp;             /* methods [first, first+count) */\n");
    out.push_str("typedef struct { uint16_t name, id, req, nreq, resp, nresp; } cat_method; /* fields of cat_fields */\n");
    out.push_str("typedef struct { uint16_t name, tag; uint8_t kind, record; } cat_field;     /* record: 1 + index in cat_records */\n");
    out.push_str("typedef struct { uint16_t name, first, count; } cat_record;\n");
    out.push_str(&format!(
        "#define CAT_COMPS {}\n#define CAT_METHODS {}\n#define CAT_FIELDS {}\n#define CAT_RECORDS {}\n",
        component_rows.len(),
        method_rows.len(),
        fields.len(),
        record_rows.len()
    ));
    out.push_str(&format!(
        "static const cat_comp cat_comps[CAT_COMPS] = {{{}}};\n",
        join(component_rows.iter().map(|(a, b, c, d)| format!("{{{a},{b},{c},{d}}}")).collect())
    ));
    out.push_str(&format!(
        "static const cat_method cat_methods[CAT_METHODS + 1] = {{{}, {{0,0,0,0,0,0}}}};\n",
        join(method_rows.iter().map(|(a, b, c, d, e, f)| format!("{{{a},{b},{c},{d},{e},{f}}}")).collect())
    ));
    out.push_str(&format!(
        "static const cat_field cat_fields[CAT_FIELDS + 1] = {{{}, {{0,0,0,0}}}};\n",
        join(fields.iter().map(|(a, b, c, d)| format!("{{{a},{b},{c},{d}}}")).collect())
    ));
    out.push_str(&format!(
        "static const cat_record cat_records[CAT_RECORDS + 1] = {{{}, {{0,0,0}}}};\n",
        join(record_rows.iter().map(|(a, b, c)| format!("{{{a},{b},{c}}}")).collect())
    ));
    out
}

