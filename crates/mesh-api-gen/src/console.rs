// Native calls: the part of `api.json` (`x-c`) a console needs to call a function of a native table from text.

use serde_json::Value;

const NK_UINT: u8 = 0;
const NK_INT: u8 = 1;
const NK_BOOL: u8 = 2;
const NK_TEXT: u8 = 3;
const NK_BYTES: u8 = 4;
const NK_SIZE: u8 = 5;

/// The C header of the native calls of one or more `api.json` documents: for each method with `x-c`, the table to look up
/// with `get_component`, the member's offset in it, its parameters, and the layout of the structs they point at (field tag,
/// offset, size, kind, length field). A console fills the request struct from the tagged fields of a line, calls through
/// the member, and renders the output struct back as tagged fields, with no code per function.
pub fn console_native(apis: &[Value], sources: &[String], pointer_width: u64) -> anyhow::Result<String> {
    use anyhow::{Context, bail};
    let mut pool = Pool { bytes: vec![0], offsets: BTreeMap::new() };
    // struct (by native name) -> index, fields
    let mut structs: Vec<(String, u64, Vec<[u64; 7]>)> = Vec::new(); // size, [tag, offset, size, kind, len_size, len_offset, signed]
    let mut methods: Vec<[u64; 7]> = Vec::new(); // comp, method, table, member, first param, nparams, 0
    let mut params: Vec<[u64; 5]> = Vec::new(); // role, struct or scalar size, scalar signed (kind), tag, 0
    for api in apis {
        let types = api["types"].as_array().cloned().unwrap_or_default();
        let component_of = |name: &str| api["components"].as_array().and_then(|c| c.iter().find(|c| c["name"] == name)).and_then(|c| c["index"].as_u64());
        for method in api["methods"].as_array().cloned().unwrap_or_default() {
            let Some(x) = method.get("x-c") else { continue };
            let name = method["name"].as_str().unwrap_or_default();
            let comp = component_of(method["component"].as_str().unwrap_or_default()).with_context(|| format!("{name}: no component index"))?;
            let index = method["index"].as_u64().with_context(|| format!("{name}: no method index"))?;
            // the response fields, by name, to find the tag of a scalar output
            let response_fields: Vec<Value> = match method["response"]["type"].as_str() {
                Some(t) => types.iter().find(|ty| ty["name"] == t).and_then(|ty| ty["fields"].as_array().cloned()).unwrap_or_default(),
                None => method["response"]["fields"].as_array().cloned().unwrap_or_default(),
            };
            let first = params.len();
            for p in x["params"].as_array().cloned().unwrap_or_default() {
                let role = match p["role"].as_str() {
                    Some("ctx") => 0,
                    Some("in") => 1,
                    Some("out") => 2,
                    other => bail!("{name}: parameter role {other:?} is not supported"),
                };
                if role == 0 {
                    params.push([0, 0, 0, 0, 0]);
                    continue;
                }
                let ty = p["type"].as_str().unwrap_or_default();
                if let Some(record) = types.iter().find(|t| t["x-c"]["rust"] == ty) {
                    let at = match structs.iter().position(|s| s.0 == ty) {
                        Some(at) => at,
                        None => {
                            let mut rows = Vec::new();
                            if let Some(sf) = record["x-c"].get("size_field") {
                                rows.push([0, sf["offset"].as_u64().unwrap_or(0), sf["size"].as_u64().unwrap_or(4), NK_SIZE as u64, 0, 0, 0]);
                            }
                            for f in record["fields"].as_array().cloned().unwrap_or_default() {
                                let c = &f["x-c"];
                                let native = c["kind"].as_str().unwrap_or_default();
                                let api_type = f["type"].as_str().unwrap_or_default();
                                let signed = native.starts_with('i') && native != "int";
                                let kind = match (api_type, native) {
                                    ("string", _) => NK_TEXT,
                                    ("bytes", _) => NK_BYTES,
                                    ("bool", _) => NK_BOOL,
                                    _ if signed => NK_INT,
                                    _ => NK_UINT,
                                };
                                let len = c.get("len_field");
                                rows.push([
                                    f["tag"].as_u64().unwrap_or(0),
                                    c["offset"].as_u64().unwrap_or(0),
                                    c["size"].as_u64().unwrap_or(0),
                                    kind as u64,
                                    len.map_or(0, |l| l["size"].as_u64().unwrap_or(0)),
                                    len.map_or(0, |l| l["offset"].as_u64().unwrap_or(0)),
                                    u64::from(signed),
                                ]);
                            }
                            structs.push((ty.to_owned(), record["x-c"]["size"].as_u64().unwrap_or(0), rows));
                            structs.len() - 1
                        }
                    };
                    params.push([role, 0x100 + at as u64, 0, 0, 0]);
                } else {
                    // a scalar output, mapped to the response field of the same name
                    let bits: u64 = ty[1..].parse().with_context(|| format!("{name}: parameter {} has the type {ty}", p["name"]))?;
                    let tag = if p["mapped"] == false {
                        0
                    } else {
                        response_fields.iter().find(|f| f["name"] == p["name"]).and_then(|f| f["tag"].as_u64()).unwrap_or(0)
                    };
                    params.push([role, bits / 8, u64::from(ty.starts_with('i')), tag, 0]);
                }
            }
            let table = pool.name(x["component"].as_str().unwrap_or_default());
            // a component table is {version: u32, size: u32} followed by function pointers: the member is a slot, whose byte
            // offset depends on the pointer width of the target
            let offset = x["offset"].as_u64().unwrap_or(0);
            if offset < 8 || (offset - 8) % pointer_width != 0 {
                bail!("{name}: member offset {offset} is not a pointer slot after the 8-byte table header");
            }
            methods.push([comp, index, table as u64, (offset - 8) / pointer_width, first as u64, (params.len() - first) as u64, 0]);
        }
    }
    let mut out = String::new();
    out.push_str(&format!("/* GENERATED by mesh-api-gen (--out-console-native) from {}. Do not edit. */\n#pragma once\n\n#include <stdint.h>\n\n", sources.join(", ")));
    out.push_str(&format!("#define NAT_K_UINT {NK_UINT}\n#define NAT_K_INT {NK_INT}\n#define NAT_K_BOOL {NK_BOOL}\n#define NAT_K_TEXT {NK_TEXT}\n#define NAT_K_BYTES {NK_BYTES}\n#define NAT_K_SIZE {NK_SIZE}\n"));
    out.push_str("/* parameter roles */\n#define NAT_CTX 0\n#define NAT_IN 1\n#define NAT_OUT 2\n");
    out.push_str("/* native calls of the API: get_component(table), the function pointer in slot `slot` of that table (after its 8-byte
 * {version, size} header); params are\n * (role, struct index + 0x100 | scalar size in bytes, scalar signed, response tag of a scalar output) */\n");
    out.push_str(&format!(
        "static const char nat_pool[{}] = {{{}}};\n",
        pool.bytes.len(),
        pool.bytes.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", ")
    ));
    out.push_str("typedef struct { uint16_t comp, method, table, slot, first_param, nparams; } nat_method;\n");
    out.push_str("typedef struct { uint16_t role, what, is_signed, tag; } nat_param;\n");
    out.push_str("typedef struct { uint16_t size, first, count; } nat_struct;\n");
    out.push_str("typedef struct { uint16_t tag, offset, size; uint8_t kind, len_size; uint16_t len_offset; uint8_t is_signed; } nat_field;\n");
    let join = |rows: Vec<String>| rows.join(", ");
    out.push_str(&format!("#define NAT_METHODS {}\n#define NAT_PARAMS {}\n#define NAT_STRUCTS {}\n", methods.len(), params.len(), structs.len()));
    let fields: Vec<&[u64; 7]> = structs.iter().flat_map(|s| s.2.iter()).collect();
    out.push_str(&format!("#define NAT_FIELDS {}\n", fields.len()));
    out.push_str(&format!(
        "static const nat_method nat_methods[NAT_METHODS + 1] = {{{}, {{0,0,0,0,0,0}}}};\n",
        join(methods.iter().map(|m| format!("{{{},{},{},{},{},{}}}", m[0], m[1], m[2], m[3], m[4], m[5])).collect())
    ));
    out.push_str(&format!(
        "static const nat_param nat_params[NAT_PARAMS + 1] = {{{}, {{0,0,0,0}}}};\n",
        join(params.iter().map(|p| format!("{{{},{},{},{}}}", p[0], p[1], p[2], p[3])).collect())
    ));
    let mut first = 0;
    let rows: Vec<String> = structs
        .iter()
        .map(|s| {
            let row = format!("{{{},{},{}}}", s.1, first, s.2.len());
            first += s.2.len();
            row
        })
        .collect();
    out.push_str(&format!("static const nat_struct nat_structs[NAT_STRUCTS + 1] = {{{}, {{0,0,0}}}};\n", join(rows)));
    out.push_str(&format!(
        "static const nat_field nat_fields[NAT_FIELDS + 1] = {{{}, {{0,0,0,0,0,0,0}}}};\n",
        join(fields.iter().map(|f| format!("{{{},{},{},{},{},{},{}}}", f[0], f[1], f[2], f[3], f[4], f[5], f[6])).collect())
    ));
    Ok(out)
}
