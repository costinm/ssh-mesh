//! Passive component directory and lazy on-demand handler activation.
//!
//! Components are declared passively—via compile-time [`ComponentSpec`] tables
//! in `.rodata`, `.manifest` CBOR files on disk, or `tools.json` catalogs—with
//! zero component initialization code executed at startup. When a request or
//! stream arrives for a component, [`ComponentDirectory`] activates its handler
//! on demand (via a Rust factory, WASM runtime loader, or `.so` loader), tracks
//! in-flight calls and streams, and can reclaim idle instances via
//! [`ComponentDirectory::evict_idle`].

use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::sync::atomic::{AtomicU64, AtomicUsize, Ordering};
use std::time::{Duration, Instant};

use anyhow::{Context, Result, anyhow, bail};
use mesh_api::cbor::{Decoder, Encoder};
use mesh_api::component::{ComponentSpec, MethodExecution, MethodSpec};
use mesh_api::envelope::{Name, encode_error_header};
use parking_lot::RwLock;
use serde_json::Value;
use tokio::io::AsyncWriteExt;

use crate::client::MeshStream;
use crate::framed_stream::{FramedStream, OwnedEnvelope, read_envelope_prefix};
use crate::registry::ServiceRegistry;
use crate::route::MeshRouter;
use crate::tagged::{NameOrTag, RecordKind, TaggedRecord};
use crate::wire::{TaggedRecordHandler, response_error, response_ok};

/// Borrowed view of a resolved method descriptor passed to [`ComponentHandler`].
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct MethodCall<'a> {
    /// Method name within the component (empty only if invoked by numeric ID
    /// against a stripped module manifest that omits method names).
    pub name: &'a str,
    /// Optional compact numeric method ID.
    pub id: Option<u32>,
    /// Execution shape (`Unary`, `Blocking`, or `Stream`).
    pub execution: MethodExecution,
    /// Optional caller-supplied request timeout in milliseconds (envelope key `8`).
    pub timeout_ms: Option<u64>,
}

impl<'a> MethodCall<'a> {
    /// Construct from a static [`MethodSpec`].
    pub const fn from_spec(spec: &'a MethodSpec) -> Self {
        Self {
            name: spec.name,
            id: spec.id,
            execution: spec.execution,
            timeout_ms: None,
        }
    }

    /// Attach an optional caller request timeout in milliseconds.
    pub const fn with_timeout_ms(mut self, timeout_ms: Option<u64>) -> Self {
        self.timeout_ms = timeout_ms;
        self
    }

    /// Return whether this method opens a bidirectional body stream.
    pub const fn is_stream(&self) -> bool {
        matches!(self.execution, MethodExecution::Stream)
    }
}

/// Owned runtime method metadata parsed passively from a `.manifest` or `tools.json` file.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DynamicMethodSpec {
    /// Method name within its component.
    pub name: String,
    /// Optional compact numeric method ID.
    pub id: Option<u32>,
    /// Execution mode (`Unary`, `Blocking`, or `Stream`).
    pub execution: MethodExecution,
}

impl DynamicMethodSpec {
    /// Return whether `method` matches either [`Self::name`] or [`Self::id`].
    pub fn matches(&self, method: Name<'_>) -> bool {
        match method {
            Name::Text(bytes) => self.name.as_bytes() == bytes,
            Name::Tag(tag) => u32::try_from(tag)
                .ok()
                .is_some_and(|id| self.id == Some(id)),
            Name::Bytes(_) => false,
        }
    }
}

/// Owned runtime component metadata parsed passively from a `.manifest` or `tools.json` file
/// without loading or executing the underlying WASM or `.so` module.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DynamicComponentSpec {
    /// Canonical component name or path prefix.
    pub name: String,
    /// Optional compact numeric wire component ID.
    pub id: Option<u32>,
    /// Additional wire `(component_id, version)` pairs hosted by a multi-component XIP module
    /// (manifest key `13`).
    pub extra_wire_ids: Vec<(u32, u32)>,
    /// Component protocol version (defaults to `1`).
    pub version: u32,
    /// Optional method ID designated as the module stream handler (manifest key `10`).
    pub stream_method_id: Option<u32>,
    /// Methods declared in the manifest (may be empty for stripped binary module headers).
    pub methods: Vec<DynamicMethodSpec>,
}

impl DynamicComponentSpec {
    /// Decode a passive CBOR `.manifest` generated by `mesh-api-gen --out-manifest`
    /// or `esp-xip-modules` `tools/mkmod.py`.
    ///
    /// Keys recognized:
    /// - `1`: component/module name (`text`)
    /// - `2`: primary component numeric ID (`uint`)
    /// - `3`: method catalog `[{1: id, 2: name, ...}, ...]`
    /// - `8`: version (`uint`, defaults to `1`)
    /// - `10`: stream method ID (`uint`)
    /// - `13`: wire components `[[component_id, version], ...]`
    pub fn from_manifest_cbor(bytes: &[u8]) -> Result<Self> {
        let mut dec = Decoder::new(bytes);
        let (major, count) = dec
            .head()
            .ok_or_else(|| anyhow!("manifest is not a valid CBOR item"))?;
        if major != 5 {
            bail!("manifest root must be a CBOR map");
        }
        let mut name: Option<String> = None;
        let mut id: Option<u32> = None;
        let mut version: u32 = 1;
        let mut stream_method_id: Option<u32> = None;
        let mut extra_wire_ids: Vec<(u32, u32)> = Vec::new();
        let mut methods: Vec<DynamicMethodSpec> = Vec::new();

        for _ in 0..count {
            let key = dec
                .uint()
                .ok_or_else(|| anyhow!("manifest map key must be uint"))?;
            match key {
                1 => {
                    let raw = dec
                        .text_ref()
                        .ok_or_else(|| anyhow!("manifest key 1 (name) must be text"))?;
                    name = Some(
                        std::str::from_utf8(raw)
                            .context("manifest name is not UTF-8")?
                            .to_owned(),
                    );
                }
                2 => {
                    let v = dec
                        .uint()
                        .ok_or_else(|| anyhow!("manifest key 2 (component id) must be uint"))?;
                    id = Some(u32::try_from(v).context("manifest component id out of u32 range")?);
                }
                3 => {
                    let (arr_major, arr_len) = dec
                        .head()
                        .ok_or_else(|| anyhow!("manifest key 3 (methods) invalid"))?;
                    if arr_major != 4 {
                        bail!("manifest key 3 (methods) must be an array");
                    }
                    for _ in 0..arr_len {
                        let (m_major, m_entries) = dec
                            .head()
                            .ok_or_else(|| anyhow!("manifest method entry must be a map"))?;
                        if m_major != 5 {
                            bail!("manifest method entry must be a map");
                        }
                        let mut m_id: Option<u32> = None;
                        let mut m_name: Option<String> = None;
                        for _ in 0..m_entries {
                            let m_key = dec
                                .uint()
                                .ok_or_else(|| anyhow!("manifest method key must be uint"))?;
                            match m_key {
                                1 => {
                                    let v = dec.uint().ok_or_else(|| {
                                        anyhow!("manifest method id must be uint")
                                    })?;
                                    m_id = Some(u32::try_from(v)?);
                                }
                                2 => {
                                    let raw = dec.text_ref().ok_or_else(|| {
                                        anyhow!("manifest method name must be text")
                                    })?;
                                    m_name = Some(std::str::from_utf8(raw)?.to_owned());
                                }
                                _ => {
                                    dec.skip()
                                        .ok_or_else(|| anyhow!("corrupt manifest method field"))?;
                                }
                            }
                        }
                        if let Some(m_name) = m_name {
                            methods.push(DynamicMethodSpec {
                                name: m_name,
                                id: m_id,
                                execution: MethodExecution::Unary,
                            });
                        }
                    }
                }
                8 => {
                    let v = dec
                        .uint()
                        .ok_or_else(|| anyhow!("manifest key 8 (version) must be uint"))?;
                    version = u32::try_from(v).context("manifest version out of u32 range")?;
                }
                10 => {
                    let v = dec
                        .uint()
                        .ok_or_else(|| anyhow!("manifest key 10 (stream) must be uint"))?;
                    stream_method_id = Some(u32::try_from(v)?);
                }
                13 => {
                    let (arr_major, arr_len) = dec
                        .head()
                        .ok_or_else(|| anyhow!("manifest key 13 (wire) invalid"))?;
                    if arr_major != 4 {
                        bail!("manifest key 13 (wire) must be an array");
                    }
                    for _ in 0..arr_len {
                        let (pair_major, pair_len) = dec
                            .head()
                            .ok_or_else(|| anyhow!("manifest wire entry must be an array"))?;
                        if pair_major != 4 || pair_len < 2 {
                            bail!("manifest wire entry must be [id, version]");
                        }
                        let cid = u32::try_from(
                            dec.uint()
                                .ok_or_else(|| anyhow!("wire component id must be uint"))?,
                        )?;
                        let ver = u32::try_from(
                            dec.uint()
                                .ok_or_else(|| anyhow!("wire component version must be uint"))?,
                        )?;
                        for _ in 2..pair_len {
                            dec.skip()
                                .ok_or_else(|| anyhow!("corrupt manifest wire tuple"))?;
                        }
                        extra_wire_ids.push((cid, ver));
                    }
                }
                _ => {
                    dec.skip()
                        .ok_or_else(|| anyhow!("corrupt manifest value for key {key}"))?;
                }
            }
        }

        if let Some(stream_id) = stream_method_id {
            for method in &mut methods {
                if method.id == Some(stream_id) {
                    method.execution = MethodExecution::Stream;
                }
            }
        }

        let name = name.ok_or_else(|| anyhow!("manifest missing key 1 (component name)"))?;
        Ok(Self {
            name,
            id,
            extra_wire_ids,
            version,
            stream_method_id,
            methods,
        })
    }

    /// Return whether `component` matches this spec's name, primary ID, or hosted wire IDs.
    pub fn matches(&self, component: Name<'_>) -> bool {
        match component {
            Name::Text(bytes) => self.name.as_bytes() == bytes,
            Name::Tag(tag) => {
                let Ok(cid) = u32::try_from(tag) else {
                    return false;
                };
                self.id == Some(cid)
                    || self.extra_wire_ids.iter().any(|(wire_id, _)| *wire_id == cid)
            }
            Name::Bytes(_) => false,
        }
    }
}

/// Active instance of a component (compiled-in Rust struct, loaded WASM slot, or `.so` plugin).
///
/// Implementors may override either [`Self::call_json`], [`Self::call_cbor`], or both
/// (code generated by `mesh-api-gen --out-component` implements both directly without
/// intermediate conversion).
#[async_trait::async_trait]
pub trait ComponentHandler: Send + Sync + 'static {
    /// Handle a unary request with structured JSON parameters.
    async fn call_json(&self, method: MethodCall<'_>, params: Value) -> Result<Value> {
        let cbor_fields = crate::cbor::encode_value_bytes(&params)?;
        let out_bytes = self.call_cbor(method, &cbor_fields).await?;
        crate::cbor::decode_value_bytes(&out_bytes)
    }

    /// Handle a unary request whose `fields` payload is a CBOR map (`&[u8]`),
    /// returning the encoded CBOR response result item (`Vec<u8>`).
    async fn call_cbor(&self, method: MethodCall<'_>, fields_cbor: &[u8]) -> Result<Vec<u8>> {
        let params = crate::cbor::decode_value_bytes(fields_cbor)?;
        let result = self.call_json(method, params).await?;
        crate::cbor::encode_value_bytes(&result)
    }

    /// Handle an incoming bidirectional stream (`MethodExecution::Stream`) whose opening
    /// envelope prefix has already been decoded in a single pass.
    async fn open_stream(
        &self,
        method: MethodCall<'_>,
        _envelope: OwnedEnvelope,
        _stream: FramedStream<Box<dyn MeshStream>>,
    ) -> Result<()> {
        bail!("method `{}` does not accept streams", method.name)
    }
}

/// Pluggable on-demand loader for external module artifacts (for example `xip-runtime-host`
/// `.wasm` modules or `dlopen` `.so` shared libraries).
#[async_trait::async_trait]
pub trait ModuleLoader: Send + Sync + 'static {
    /// Load and instantiate the module at `module_path` when the first request targets `spec`.
    async fn load(
        &self,
        spec: &DynamicComponentSpec,
        module_path: &Path,
    ) -> Result<Arc<dyn ComponentHandler>>;
}

/// Compile-time descriptor for a built-in Rust component (lives in `.rodata`).
///
/// Registering a slice of [`StaticComponent`]s executes zero component code at boot;
/// `create` is a plain function pointer invoked only when the first request arrives.
pub struct StaticComponent<Ctx = ()> {
    /// Passive generated metadata from `API.md`.
    pub spec: &'static ComponentSpec,
    /// Constructor called lazily on the first matching request.
    pub create: fn(&Ctx) -> Arc<dyn ComponentHandler>,
}

impl<Ctx> Clone for StaticComponent<Ctx> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<Ctx> Copy for StaticComponent<Ctx> {}

enum SpecKind {
    Static(&'static ComponentSpec),
    Dynamic(DynamicComponentSpec),
}

impl SpecKind {
    fn name(&self) -> &str {
        match self {
            Self::Static(spec) => spec.name,
            Self::Dynamic(spec) => &spec.name,
        }
    }

    fn id(&self) -> Option<u32> {
        match self {
            Self::Static(spec) => spec.id,
            Self::Dynamic(spec) => spec.id,
        }
    }

    fn matches(&self, component: Name<'_>) -> bool {
        match self {
            Self::Static(spec) => spec.matches(component),
            Self::Dynamic(spec) => spec.matches(component),
        }
    }

    fn resolve_method<'a>(&'a self, method: Name<'a>) -> Option<MethodCall<'a>> {
        match self {
            Self::Static(spec) => spec.find_method(method).map(MethodCall::from_spec),
            Self::Dynamic(spec) => {
                if let Some(found) = spec.methods.iter().find(|m| m.matches(method)) {
                    return Some(MethodCall {
                        name: &found.name,
                        id: found.id,
                        execution: found.execution,
                        timeout_ms: None,
                    });
                }
                // Stripped binary module manifests (keys 1, 2, 8, 10, 13 only) omit the
                // per-method catalog and dispatch inside the module's own xip_handle match.
                if spec.methods.is_empty() {
                    return match method {
                        Name::Tag(tag) => {
                            let mid = u32::try_from(tag).ok()?;
                            let execution = if spec.stream_method_id == Some(mid) {
                                MethodExecution::Stream
                            } else {
                                MethodExecution::Unary
                            };
                            Some(MethodCall {
                                name: "",
                                id: Some(mid),
                                execution,
                                timeout_ms: None,
                            })
                        }
                        Name::Text(bytes) => {
                            let name = std::str::from_utf8(bytes).ok()?;
                            Some(MethodCall {
                                name,
                                id: None,
                                execution: MethodExecution::Unary,
                                timeout_ms: None,
                            })
                        }
                        Name::Bytes(_) => None,
                    };
                }
                None
            }
        }
    }
}

enum Activator {
    Factory(Box<dyn Fn() -> Result<Arc<dyn ComponentHandler>> + Send + Sync>),
    Loader {
        path: PathBuf,
        loader: Arc<dyn ModuleLoader>,
    },
}

struct ComponentSlot {
    epoch: Instant,
    spec: SpecKind,
    activator: Activator,
    instance: RwLock<Option<Arc<dyn ComponentHandler>>>,
    activate_lock: tokio::sync::Mutex<()>,
    active_calls: AtomicUsize,
    last_used_ms: AtomicU64,
}

impl ComponentSlot {
    fn new(epoch: Instant, spec: SpecKind, activator: Activator) -> Self {
        Self {
            epoch,
            spec,
            activator,
            instance: RwLock::new(None),
            activate_lock: tokio::sync::Mutex::new(()),
            active_calls: AtomicUsize::new(0),
            last_used_ms: AtomicU64::new(0),
        }
    }

    fn now_ms(&self) -> u64 {
        u64::try_from(self.epoch.elapsed().as_millis()).unwrap_or(u64::MAX)
    }

    fn is_active(&self) -> bool {
        self.instance.read().is_some()
    }

    async fn acquire(self: &Arc<Self>) -> Result<ActiveComponentGuard> {
        // Fast path: already instantiated. Hold the read lock while incrementing
        // `active_calls` so `evict_idle` cannot race and clear the slot underneath us.
        {
            let guard = self.instance.read();
            if let Some(handler) = guard.as_ref() {
                self.active_calls.fetch_add(1, Ordering::AcqRel);
                self.last_used_ms.store(self.now_ms(), Ordering::Release);
                return Ok(ActiveComponentGuard {
                    slot: Arc::clone(self),
                    handler: Arc::clone(handler),
                });
            }
        }

        // Cold path: serialize activation for this component only.
        let _activating = self.activate_lock.lock().await;
        {
            let guard = self.instance.read();
            if let Some(handler) = guard.as_ref() {
                self.active_calls.fetch_add(1, Ordering::AcqRel);
                self.last_used_ms.store(self.now_ms(), Ordering::Release);
                return Ok(ActiveComponentGuard {
                    slot: Arc::clone(self),
                    handler: Arc::clone(handler),
                });
            }
        }

        let created = match &self.activator {
            Activator::Factory(factory) => factory()?,
            Activator::Loader { path, loader } => {
                let SpecKind::Dynamic(spec) = &self.spec else {
                    bail!("loader activator requires a dynamic component spec");
                };
                loader.load(spec, path).await?
            }
        };

        let mut write_guard = self.instance.write();
        self.active_calls.fetch_add(1, Ordering::AcqRel);
        self.last_used_ms.store(self.now_ms(), Ordering::Release);
        *write_guard = Some(Arc::clone(&created));
        Ok(ActiveComponentGuard {
            slot: Arc::clone(self),
            handler: created,
        })
    }

    fn try_evict_idle(&self, now_ms: u64, max_idle_ms: u64) -> bool {
        if self.active_calls.load(Ordering::Acquire) != 0 {
            return false;
        }
        let last = self.last_used_ms.load(Ordering::Acquire);
        if now_ms.saturating_sub(last) < max_idle_ms {
            return false;
        }
        let mut guard = self.instance.write();
        if self.active_calls.load(Ordering::Acquire) != 0 {
            return false;
        }
        let last_recheck = self.last_used_ms.load(Ordering::Acquire);
        if now_ms.saturating_sub(last_recheck) < max_idle_ms {
            return false;
        }
        guard.take().is_some()
    }
}

struct ActiveComponentGuard {
    slot: Arc<ComponentSlot>,
    handler: Arc<dyn ComponentHandler>,
}

impl Drop for ActiveComponentGuard {
    fn drop(&mut self) {
        self.slot
            .last_used_ms
            .store(self.slot.now_ms(), Ordering::Release);
        self.slot.active_calls.fetch_sub(1, Ordering::AcqRel);
    }
}

/// Passive host directory of compiled-in components, WASM modules, and `.so` plugins.
///
/// No component handler is instantiated during registration or manifest scanning;
/// handlers are created lazily when a matching request or stream arrives.
pub struct ComponentDirectory {
    epoch: Instant,
    slots: RwLock<Vec<Arc<ComponentSlot>>>,
    service_registry: Option<ServiceRegistry>,
    router: Option<Arc<MeshRouter>>,
}

impl Default for ComponentDirectory {
    fn default() -> Self {
        Self::new()
    }
}

impl ComponentDirectory {
    /// Create an empty passive component directory.
    pub fn new() -> Self {
        Self {
            epoch: Instant::now(),
            slots: RwLock::new(Vec::new()),
            service_registry: None,
            router: None,
        }
    }

    /// Populate a passive directory from a compile-time slice of [`StaticComponent`]s.
    ///
    /// None of the `create` functions are called until a request targets that component.
    pub fn from_static<Ctx>(entries: &[StaticComponent<Ctx>], ctx: Ctx) -> Self
    where
        Ctx: Clone + Send + Sync + 'static,
    {
        let dir = Self::new();
        for entry in entries {
            let create = entry.create;
            let ctx_clone = ctx.clone();
            dir.register_lazy(entry.spec, move || Ok(create(&ctx_clone)));
        }
        dir
    }

    /// Attach a [`ServiceRegistry`] so common lifecycle/trace methods (`mesh.*`, `trace.*`)
    /// are answered automatically on `TaggedRecord` sessions.
    pub fn with_service_registry(mut self, registry: ServiceRegistry) -> Self {
        self.service_registry = Some(registry);
        self
    }

    /// Attach a [`MeshRouter`] so directed requests carrying a `to` field are forwarded.
    pub fn with_router(mut self, router: Arc<MeshRouter>) -> Self {
        self.router = Some(router);
        self
    }

    /// Passively register a compiled-in component with a lazy factory closure.
    pub fn register_lazy<F>(&self, spec: &'static ComponentSpec, factory: F)
    where
        F: Fn() -> Result<Arc<dyn ComponentHandler>> + Send + Sync + 'static,
    {
        let slot = Arc::new(ComponentSlot::new(
            self.epoch,
            SpecKind::Static(spec),
            Activator::Factory(Box::new(factory)),
        ));
        self.slots.write().push(slot);
    }

    /// Passively register a compiled-in component whose handler implements [`Default`].
    pub fn register_default<H>(&self, spec: &'static ComponentSpec)
    where
        H: ComponentHandler + Default,
    {
        self.register_lazy(spec, || Ok(Arc::new(H::default())));
    }

    /// Passively register an external module (`.wasm` or `.so`) backed by [`ModuleLoader`].
    pub fn register_dynamic(
        &self,
        spec: DynamicComponentSpec,
        module_path: PathBuf,
        loader: Arc<dyn ModuleLoader>,
    ) {
        let slot = Arc::new(ComponentSlot::new(
            self.epoch,
            SpecKind::Dynamic(spec),
            Activator::Loader {
                path: module_path,
                loader,
            },
        ));
        self.slots.write().push(slot);
    }

    /// Passively scan `dir` for `*.manifest` CBOR files paired with `<stem>.<module_ext>`
    /// artifacts (for example `"wasm"` for `xip-runtime-host` or `"so"` for native plugins)
    /// and register them for on-demand loading.
    ///
    /// Returns the number of module manifests registered. Zero modules are loaded at scan time.
    pub fn scan_manifest_dir(
        &self,
        dir: &Path,
        module_ext: &str,
        loader: Arc<dyn ModuleLoader>,
    ) -> Result<usize> {
        let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)
            .with_context(|| format!("read component manifest directory {}", dir.display()))?
            .filter_map(|entry| entry.ok().map(|e| e.path()))
            .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("manifest"))
            .collect();
        entries.sort();

        let ext_clean = module_ext.trim_start_matches('.');
        let mut count = 0;
        for manifest_path in entries {
            let module_path = manifest_path.with_extension(ext_clean);
            if !module_path.exists() {
                continue;
            }
            let bytes = std::fs::read(&manifest_path)
                .with_context(|| format!("read manifest {}", manifest_path.display()))?;
            let spec = DynamicComponentSpec::from_manifest_cbor(&bytes)
                .with_context(|| format!("decode manifest {}", manifest_path.display()))?;
            self.register_dynamic(spec, module_path, Arc::clone(&loader));
            count += 1;
        }
        Ok(count)
    }

    /// Return the total number of passively registered components.
    pub fn component_count(&self) -> usize {
        self.slots.read().len()
    }

    /// List the canonical names of all registered components in registration order.
    pub fn component_names(&self) -> Vec<String> {
        self.slots
            .read()
            .iter()
            .map(|slot| slot.spec.name().to_owned())
            .collect()
    }

    /// List `(component_id, method_id, "component.method")` catalog rows for all passively
    /// registered methods that carry compact numeric IDs, sorted and deduplicated by
    /// `(component_id, method_id)`. Zero component handlers are instantiated.
    pub fn catalog_rows(&self) -> Vec<(u64, u64, String)> {
        let mut rows = Vec::new();
        for slot in self.slots.read().iter() {
            match &slot.spec {
                SpecKind::Static(spec) => {
                    if let Some(cid) = spec.id {
                        for m in spec.methods {
                            if let Some(mid) = m.id {
                                rows.push((
                                    u64::from(cid),
                                    u64::from(mid),
                                    format!("{}.{}", spec.name, m.name),
                                ));
                            }
                        }
                    }
                }
                SpecKind::Dynamic(spec) => {
                    if let Some(cid) = spec.id {
                        for m in &spec.methods {
                            if let Some(mid) = m.id {
                                rows.push((
                                    u64::from(cid),
                                    u64::from(mid),
                                    format!("{}.{}", spec.name, m.name),
                                ));
                            }
                        }
                    }
                }
            }
        }
        rows.sort_by_key(|(cid, mid, _)| (*cid, *mid));
        rows.dedup_by_key(|(cid, mid, _)| (*cid, *mid));
        rows
    }

    /// Return whether any passively registered component matches `component`
    /// (by string name or numeric ID), without instantiating it.
    pub fn has_component(&self, component: Name<'_>) -> bool {
        self.find_slot(component).is_some()
    }

    /// Return whether the named component currently has an instantiated handler in memory.
    pub fn is_active(&self, component: &str) -> bool {
        self.find_slot(Name::Text(component.as_bytes()))
            .is_some_and(|slot| slot.is_active())
    }

    /// Return the number of currently executing calls/streams on `component`.
    pub fn active_calls(&self, component: &str) -> usize {
        self.find_slot(Name::Text(component.as_bytes()))
            .map_or(0, |slot| slot.active_calls.load(Ordering::Acquire))
    }

    /// Drop instantiated handlers that have zero in-flight calls/streams and have been
    /// idle for at least `max_idle`. Returns the number of handlers reclaimed.
    ///
    /// Subsequent requests for an evicted component transparently re-activate it.
    pub fn evict_idle(&self, max_idle: Duration) -> usize {
        let now_ms = u64::try_from(self.epoch.elapsed().as_millis()).unwrap_or(u64::MAX);
        let max_idle_ms = u64::try_from(max_idle.as_millis()).unwrap_or(u64::MAX);
        let slots: Vec<Arc<ComponentSlot>> = self.slots.read().clone();
        slots
            .into_iter()
            .filter(|slot| slot.try_evict_idle(now_ms, max_idle_ms))
            .count()
    }

    fn find_slot(&self, component: Name<'_>) -> Option<Arc<ComponentSlot>> {
        self.slots
            .read()
            .iter()
            .find(|slot| slot.spec.matches(component))
            .cloned()
    }

    /// Invoke a unary method using string `component` and `method` names and JSON parameters.
    pub async fn call_json(&self, component: &str, method: &str, params: Value) -> Result<Value> {
        let slot = self
            .find_slot(Name::Text(component.as_bytes()))
            .ok_or_else(|| anyhow!("unknown component `{component}`"))?;
        let method_call = slot
            .spec
            .resolve_method(Name::Text(method.as_bytes()))
            .ok_or_else(|| anyhow!("unknown method `{component}.{method}`"))?;
        if method_call.is_stream() {
            bail!("method `{component}.{method}` requires a stream");
        }
        let guard = slot.acquire().await?;
        guard.handler.call_json(method_call, params).await
    }

    /// Invoke a unary method using borrowed envelope identifiers (string or numeric) and a
    /// CBOR-encoded fields map (`&[u8]`, defaulting to `{}` if empty).
    pub async fn call_cbor(
        &self,
        component: Name<'_>,
        method: Name<'_>,
        fields_cbor: &[u8],
    ) -> Result<Vec<u8>> {
        self.call_cbor_with_timeout(component, method, fields_cbor, None)
            .await
    }

    /// Like [`Self::call_cbor`], propagating an optional caller `timeout_ms` from envelope key `8`.
    pub async fn call_cbor_with_timeout(
        &self,
        component: Name<'_>,
        method: Name<'_>,
        fields_cbor: &[u8],
        timeout_ms: Option<u64>,
    ) -> Result<Vec<u8>> {
        let slot = self
            .find_slot(component)
            .ok_or_else(|| anyhow!("unknown component {component:?}"))?;
        let method_call = slot
            .spec
            .resolve_method(method)
            .ok_or_else(|| anyhow!("unknown method {method:?} on `{}`", slot.spec.name()))?
            .with_timeout_ms(timeout_ms);
        if method_call.is_stream() {
            bail!(
                "method `{}.{}` requires a stream",
                slot.spec.name(),
                method_call.name
            );
        }
        let payload = if fields_cbor.is_empty() {
            &[0xa0][..]
        } else {
            fields_cbor
        };
        let guard = slot.acquire().await?;
        guard.handler.call_cbor(method_call, payload).await
    }

    /// Serve all peer-opened [`quic_mux::MuxStream`]s on a `quic-mux` connection (`TcpStream`
    /// or `UnixStream`) through [`Self::serve_stream`].
    pub async fn serve_mux_connection<S>(
        self: Arc<Self>,
        stream: S,
        config: quic_mux::TokioMuxConfig,
    ) where
        S: tokio::io::AsyncRead + tokio::io::AsyncWrite + Send + 'static,
    {
        let (mux, mut acceptor) = quic_mux::TokioMux::server(stream, config);
        while let Some(mux_stream) = acceptor.accept().await {
            let dir = Arc::clone(&self);
            tokio::spawn(async move {
                if let Err(error) = dir.serve_stream(mux_stream).await {
                    tracing::debug!(%error, "component_mux_stream_failed");
                }
            });
        }
        drop(mux);
    }

    /// Accept one multiplexed or byte stream (`quic-mux`, TCP, or UDS), decode its opening
    /// envelope in a single pass, lazily activate the target component, and serve either a
    /// bidirectional [`MethodExecution::Stream`] or a single unary exchange.
    pub async fn serve_stream<S>(&self, stream: S) -> Result<()>
    where
        S: MeshStream + 'static,
    {
        let boxed: Box<dyn MeshStream> = Box::new(stream);
        let (envelope, framed) = read_envelope_prefix(boxed).await?;
        self.serve_framed_stream(envelope, framed).await
    }

    /// Serve a stream whose opening [`OwnedEnvelope`] has already been decoded by
    /// [`read_envelope_prefix`].
    pub async fn serve_framed_stream(
        &self,
        envelope: OwnedEnvelope,
        mut framed: FramedStream<Box<dyn MeshStream>>,
    ) -> Result<()> {

        let (comp_name, meth_name, req_id, fields_opt) = {
            let Some(record) = envelope.record() else {
                let _ = framed
                    .write_all(&encode_error_header(envelope.id, b"invalid envelope"))
                    .await;
                let _ = framed.shutdown().await;
                bail!("invalid decoded envelope");
            };
            let Some(comp) = record.component else {
                let _ = framed
                    .write_all(&encode_error_header(record.id, b"missing component"))
                    .await;
                let _ = framed.shutdown().await;
                bail!("stream envelope missing component");
            };
            let Some(meth) = record.method else {
                let _ = framed
                    .write_all(&encode_error_header(record.id, b"missing method"))
                    .await;
                let _ = framed.shutdown().await;
                bail!("stream envelope missing method");
            };
            (
                owned_name(comp),
                owned_name(meth),
                record.id,
                record.fields.map(|f| f.to_vec()),
            )
        };

        let Some(slot) = self.find_slot(comp_name.as_name()) else {
            let msg = format!("unknown component {:?}", comp_name.as_name());
            write_stream_error(
                &mut framed,
                comp_name.as_name(),
                meth_name.as_name(),
                req_id,
                msg.as_bytes(),
            )
            .await?;
            return Ok(());
        };

        let meth_borrowed = meth_name.as_name();
        let Some((is_stream, method_name_owned, method_id, execution)) = slot
            .spec
            .resolve_method(meth_borrowed)
            .map(|mc| (mc.is_stream(), mc.name.to_owned(), mc.id, mc.execution))
        else {
            let msg = format!("unknown method {:?}", meth_borrowed);
            write_stream_error(
                &mut framed,
                comp_name.as_name(),
                meth_borrowed,
                req_id,
                msg.as_bytes(),
            )
            .await?;
            return Ok(());
        };

        let guard = match slot.acquire().await {
            Ok(g) => g,
            Err(error) => {
                write_stream_error(
                    &mut framed,
                    comp_name.as_name(),
                    meth_borrowed,
                    req_id,
                    error.to_string().as_bytes(),
                )
                .await?;
                return Err(error);
            }
        };

        let method_call = MethodCall {
            name: &method_name_owned,
            id: method_id,
            execution,
            timeout_ms: envelope.timeout,
        };

        if is_stream {
            return guard
                .handler
                .open_stream(method_call, envelope, framed)
                .await;
        }

        // Unary call over stream: execute `call_cbor` and write correlated response header.
        let payload = fields_opt.as_deref().unwrap_or(&[0xa0]);
        match guard.handler.call_cbor(method_call, payload).await {
            Ok(result_cbor) => {
                if let Some(id) = req_id {
                    let resp = encode_stream_response_envelope(
                        slot.spec.id(),
                        slot.spec.name(),
                        method_id,
                        &method_name_owned,
                        id,
                        &result_cbor,
                    )?;
                    framed.write_all(&resp).await?;
                }
                framed.shutdown().await?;
                Ok(())
            }
            Err(error) => {
                write_stream_error(
                    &mut framed,
                    comp_name.as_name(),
                    meth_borrowed,
                    req_id,
                    error.to_string().as_bytes(),
                )
                .await?;
                Ok(())
            }
        }
    }
}

#[async_trait::async_trait]
impl TaggedRecordHandler for ComponentDirectory {
    async fn handle_record(&self, record: TaggedRecord) -> Result<Option<TaggedRecord>> {
        if let Some(registry) = &self.service_registry
            && let Some(common_reply) = registry.dispatch_tagged(&record).await?
        {
            return Ok(Some(common_reply));
        }

        let kind = record.kind()?;
        if !matches!(kind, RecordKind::Request | RecordKind::Message) {
            bail!("component directory received non-request record");
        }

        let comp_name = name_or_tag_to_name(&record.component);
        let meth_name = name_or_tag_to_name(&record.method);
        let fields_cbor = crate::cbor::encode_record_fields(&record)?;

        match self
            .call_cbor_with_timeout(comp_name, meth_name, &fields_cbor, record.timeout)
            .await
        {
            Ok(result_cbor) => match record.id {
                Some(id) => {
                    let result_val = crate::cbor::decode_value_bytes(&result_cbor)?;
                    Ok(Some(response_ok(id, result_val)))
                }
                None => Ok(None),
            },
            Err(error) => match record.id {
                Some(id) => Ok(Some(response_error(
                    id,
                    serde_json::json!({ "message": error.to_string() }),
                ))),
                None => Err(error),
            },
        }
    }

    async fn forward_record(&self, record: TaggedRecord) -> Result<Option<TaggedRecord>> {
        if let Some(router) = &self.router {
            return router.forward_record(record).await.map(Some);
        }
        let id = record
            .id
            .context("directed request missing correlation id")?;
        Ok(Some(response_error(
            id,
            serde_json::json!({
                "error": "mesh forwarding is unavailable for this service",
                "to": record.to,
            }),
        )))
    }
}

enum OwnedName {
    Tag(u64),
    Text(Vec<u8>),
    Bytes(Vec<u8>),
}

impl OwnedName {
    fn as_name(&self) -> Name<'_> {
        match self {
            Self::Tag(tag) => Name::Tag(*tag),
            Self::Text(bytes) => Name::Text(bytes),
            Self::Bytes(bytes) => Name::Bytes(bytes),
        }
    }
}

fn owned_name(name: Name<'_>) -> OwnedName {
    match name {
        Name::Tag(tag) => OwnedName::Tag(tag),
        Name::Text(bytes) => OwnedName::Text(bytes.to_vec()),
        Name::Bytes(bytes) => OwnedName::Bytes(bytes.to_vec()),
    }
}

fn name_or_tag_to_name(value: &NameOrTag) -> Name<'_> {
    match value {
        NameOrTag::Name(text) => Name::Text(text.as_bytes()),
        NameOrTag::Tag(tag) => Name::Tag(u64::from(*tag)),
    }
}

fn encode_stream_response_envelope(
    comp_id: Option<u32>,
    comp_name: &str,
    method_id: Option<u32>,
    method_name: &str,
    id: u64,
    result_cbor: &[u8],
) -> Result<Vec<u8>> {
    let mut out = vec![0u8; result_cbor.len() + comp_name.len() + method_name.len() + 48];
    let used = {
        let mut enc = Encoder::new(&mut out);
        enc.map(4)
            .ok_or_else(|| anyhow!("response envelope buffer overflow"))?;
        enc.uint(1).ok_or_else(|| anyhow!("encode key 1"))?;
        match comp_id {
            Some(cid) => enc.uint(u64::from(cid)),
            None => enc.str(comp_name.as_bytes()),
        }
        .ok_or_else(|| anyhow!("encode component"))?;
        enc.uint(2).ok_or_else(|| anyhow!("encode key 2"))?;
        match method_id {
            Some(mid) => enc.uint(u64::from(mid)),
            None => enc.str(method_name.as_bytes()),
        }
        .ok_or_else(|| anyhow!("encode method"))?;
        enc.uint(3)
            .and_then(|()| enc.uint(id))
            .ok_or_else(|| anyhow!("encode request id"))?;
        enc.uint(6)
            .and_then(|()| enc.encoded_value(result_cbor))
            .ok_or_else(|| anyhow!("encode response result"))?;
        enc.len()
    };
    out.truncate(used);
    Ok(out)
}

async fn write_stream_error<S: tokio::io::AsyncWrite + Unpin>(
    stream: &mut S,
    comp: Name<'_>,
    meth: Name<'_>,
    id: Option<u64>,
    message: &[u8],
) -> Result<()> {
    let mut out = vec![0u8; message.len() + 96];
    let bytes = if let (Name::Tag(c), Name::Tag(m), Some(req_id)) = (comp, meth, id)
        && let Some(used) =
            mesh_api::envelope::encode_numeric_error(c, m, req_id, message, &mut out)
    {
        out.truncate(used);
        out
    } else {
        encode_error_header(id, message)
    };
    stream.write_all(&bytes).await?;
    stream.shutdown().await?;
    Ok(())
}

